videos = {}
for d in os.listdir(TR):
    v = os.path.join(TR, d, 'video.webm')
    if os.path.isfile(v):
        videos[d] = v

mapping = []
used = set()
for title, text, keys in SEGMENTS:
    files = []
    for d, v in videos.items():
        if d in used:
            continue
        if any(k in d for k in keys):
            files.append(v)
            used.add(d)
    files.sort()
    if files:
        mapping.append({"title": title, "text": text, "files": files})

unused = [d for d in videos if d not in used]
io.open(OUT, 'w', encoding='utf-8').write(json.dumps(mapping, ensure_ascii=False, indent=2))
rep = ["映射段数: %d" % len(mapping), "已用视频: %d" % len(used), "未匹配目录: %s" % (unused or '无')]
